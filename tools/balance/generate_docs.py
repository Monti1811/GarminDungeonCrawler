#!/usr/bin/env python3
"""Generate current-value documentation from the source tree.

Writes:
  documentations/enemies-values.md
  documentations/items-values.md

Usage:
  python tools/balance/generate_docs.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

WORKSPACE = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))

import auto_balance as ab  # noqa: E402

DOC_DIR = WORKSPACE / "documentations"
ITEMS_DIR = WORKSPACE / "source/Engine/Items"
ENEMIES_DIR = WORKSPACE / "source/Engine/Entities/Enemies"
DRAWABLES_XML = WORKSPACE / "resources/drawables/drawables.xml"
REPORT_JSON = WORKSPACE / "tools/balance/balance_report.json"

GENERATED_NOTE = (
    "> Auto-generated by `tools/balance/generate_docs.py` from the source tree"
    " + `tools/balance/balance_report.json`. Do not edit manually;"
    " regenerate after balance changes with `python tools/balance/generate_docs.py`."
)

TIER_NAMES = {
    0: "Steel", 1: "Bronze", 2: "Fire", 3: "Ice", 4: "Grass",
    5: "Water", 6: "Gold", 7: "Demon", 8: "Blood",
}

ATTR_SHORT = {
    "strength": "STR", "dexterity": "DEX", "intelligence": "INT",
    "constitution": "CON", "wisdom": "WIS", "charisma": "CHA",
}
ATTR_ORDER = ["strength", "dexterity", "intelligence", "constitution", "wisdom", "charisma"]
TYPE_SHORT = {
    "STRENGTH": "STR", "DEXTERITY": "DEX", "INTELLIGENCE": "INT",
    "CONSTITUTION": "CON", "WISDOM": "WIS", "CHARISMA": "CHA",
}

ENEMY_SECTIONS = [
    ("Easy", "## Easy (early depths)"),
    ("Easy/Elementals", "## Small Elementals (early depths)"),
    ("Normal", "## Normal (mid depths)"),
    ("Normal/Elementals", "## Elementals (mid-late depths)"),
    ("Hard", "## Hard (late depths)"),
    ("Custom", "## Custom"),
    ("Bosses", "## Bosses (not spawned)"),
]

FIXED_ITEM_GROUPS = [
    ("WeaponItems/Crossbow", "## Crossbows"),
    ("WeaponItems/Ammunition", "## Ammunition"),
    ("ArmorItems/Shield", "## Shields"),
    ("ArmorItems/Backpack", "## Backpacks"),
    ("ArmorItems", "## Amulets & Accessories"),
    ("Custom/WeaponItems", "## Custom Items"),
    ("ConsumableItems", "## Consumables"),
    ("SpecialItems", "## Special Items"),
]


def load_drawables() -> Dict[str, str]:
    text = DRAWABLES_XML.read_text(encoding="utf-8", errors="replace")
    return dict(re.findall(r'<bitmap id="([^"]+)" filename="([^"]+)"', text))


def img_cell(sprite: Optional[str], dmap: Dict[str, str], width: int = 32) -> str:
    if not sprite or sprite not in dmap:
        return "-"
    filename = dmap[sprite]
    return f'<img src="../resources/drawables/{filename}" width="{width}" alt="{sprite}">'


def get_sprite(text: str) -> Optional[str]:
    m = re.search(r"function getSprite.*?return\s+\$\.Rez\.Drawables\.(\w+)", text, re.S)
    return m.group(1) if m else None


def init_body(text: str) -> str:
    return ab.extract_function_body(text, "initialize") or ""


def quoted(body: str, text: str, key: str) -> str:
    m = re.search(rf'(?:self\.)?{key}\s*=\s*"([^"]*)"', body)
    if not m:
        m = re.search(rf'var\s+{key}\s+as\s+\w+\s*(?:\?\s*)?=\s*"([^"]*)"', text)
    return m.group(1) if m else ""


def parse_weight(body: str, text: str) -> Optional[float]:
    m = re.search(rf"(?:self\.)?weight\s*=\s*([0-9.]+)", body)
    if not m:
        m = re.search(rf"var\s+weight\s+as\s+\w+\s*=\s*([0-9.]+)", text)
    return float(m.group(1)) if m else None


def fmt_num(v) -> str:
    if v is None:
        return "-"
    if isinstance(v, float):
        return str(int(v)) if v.is_integer() else f"{v:g}"
    return str(v)


def bonus_text(bonus: Dict[str, int]) -> str:
    if not bonus:
        return "-"
    parts = [f"{ATTR_SHORT.get(k, k)}{bonus[k]:+d}" for k in ATTR_ORDER if k in bonus]
    parts += [
        f"{ATTR_SHORT.get(k, k)}{v:+d}"
        for k, v in sorted(bonus.items())
        if k not in ATTR_ORDER
    ]
    return " ".join(parts)


def source_link(path: Path) -> str:
    return "../" + path.relative_to(WORKSPACE).as_posix()


def write_doc(name: str, text: str) -> None:
    path = DOC_DIR / name
    try:
        path.write_text(text, encoding="utf-8", newline="\n")
    except TypeError:
        path.write_text(text, encoding="utf-8")
    print(f"wrote {path.relative_to(WORKSPACE)} ({len(text.splitlines())} lines)")


