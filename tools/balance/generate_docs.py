def build_enemies_doc(dmap: Dict[str, str]) -> str:
    enemies = ab.parse_enemy_files(WORKSPACE)
    weights = ab.parse_enemy_weights(WORKSPACE)
    report = json.loads(REPORT_JSON.read_text(encoding="utf-8"))
    config = report["config"]
    depth_win = {int(k): v["actualWinRate"] for k, v in report["depthResults"].items()}
    depth_tgt = {int(k): v["targetWinRate"] for k, v in report["depthResults"].items()}
    tol = float(config.get("tolerance", 0.05))

    lines: List[str] = [
        "# Enemy Values",
        "",
        "Current enemy stats, spawn tables and balance status.",
        "",
        GENERATED_NOTE,
        "",
        "## Roster",
        "",
        "Base stats at depth 1. Scaling with depth (`Enemy.setLevel`):",
        "`stat x (1 + (depth - 1) x scale)` with the scales from"
        " `enemyDepthScaling` (see Balance Status below).",
        "",
        "`Period` is the effective attack period in turns"
        " (energy gating + attack cooldown, lower = attacks more often).",
        "",
    ]

    groups: Dict[str, List[int]] = {}
    for eid, e in enemies.items():
        rel = e.file.relative_to(ENEMIES_DIR)
        group = rel.parent.as_posix()
        groups.setdefault(group, []).append(eid)

    ordered = [g for g, _ in ENEMY_SECTIONS if g in groups]
    ordered += sorted(g for g in groups if g not in dict(ENEMY_SECTIONS))
    for group in ordered:
        title = dict(ENEMY_SECTIONS).get(group, f"## {group}")
        lines += [
            title,
            "",
            "| Image | ID | Enemy | HP | Damage | Armor | XP | Period |",
            "|---|---:|---|---:|---:|---:|---:|---:|",
        ]
        for eid in sorted(groups[group]):
            e = enemies[eid]
            sprite = get_sprite(e.file.read_text(encoding="utf-8", errors="replace"))
            lines.append(
                f"| {img_cell(sprite, dmap)} | {eid} | {e.name} | {e.max_health} |"
                f" {e.damage} | {e.armor} | {e.kill_experience} | {e.attack_cooldown} |"
            )
        lines.append("")

    # Spawn weights
    if weights:
        tier_maxes = sorted({int(t) for entry in weights for t, _ in entry["tiers"]})  # type: ignore[index]
        lines += [
            "## Enemy Spawn Weights",
            "",
            "Current `:cost` / `:weight` tables from `EnemySpecificValues.mc`"
            " (weight for depth tier).",
            "",
            "| Enemy | Cost | " + " | ".join(f"<= {m}" for m in tier_maxes) + " |",
            "|---|---:|" + "---:|" * len(tier_maxes),
        ]

        def weight_at(tiers: List[Tuple[int, float]], depth: int) -> float:
            for tier_max, weight in tiers:
                if depth <= tier_max:
                    return weight
            return tiers[-1][1]

        def fmt_w(v: float) -> str:
            return str(int(v)) if float(v).is_integer() else f"{v:g}"

        for entry in sorted(weights, key=lambda x: int(x["id"])):  # type: ignore[arg-type]
            eid = int(entry["id"])  # type: ignore[arg-type]
            name = enemies[eid].name if eid in enemies else str(eid)
            tiers: List[Tuple[int, float]] = entry["tiers"]  # type: ignore[assignment]
            cells = " | ".join(fmt_w(weight_at(tiers, m)) for m in tier_maxes)
            lines.append(f"| {name} | {entry['cost']} | {cells} |")  # type: ignore[index]
        lines.append("")

    # Balance status
    lines += ["## Balance Status", ""]
    lines += [
        "From `tools/balance/balance_report.json` (last simulator run).",
        "",
        "| Key | Value |",
        "|---|---|",
        f"| Tolerance | +/- {tol} |",
        f"| Rounds per depth | {config.get('roundsPerDepth')} |",
        f"| Strict realism | {config.get('strictRealism')} |",
    ]
    room_size = config.get("roomSizeRange")
    if isinstance(room_size, dict):
        room_text = f"{room_size.get('min')}-{room_size.get('max')}"
    else:
        room_text = str(room_size)
    lines += [
        f"| Room size range | {room_text} |",
        f"| Rooms per depth (progression) | {config.get('roomsPerDepthForProgression')} |",
        f"| Initial attribute points | {config.get('initialAttributePoints')} |",
        "",
        "### Depth Scaling (`enemyDepthScaling`)",
        "",
        "| Stat | Scale |",
        "|---|---:|",
    ]
    scaling = config.get("enemyDepthScaling") or {}
    if isinstance(scaling, dict):
        for key, label in (
            ("healthScale", "Health"),
            ("damageScale", "Damage"),
            ("armorScale", "Armor"),
            ("xpScale", "Kill XP"),
        ):
            if key in scaling:
                lines.append(f"| {label} | {scaling[key]} |")

    targets = config.get("targetWinRateByDepth") or []
    if targets:
        lines += ["", "### Target Win Rates", "", "| Depths | Target |", "|---|---:|"]
        prev = 0
        for entry in targets:  # type: ignore[union-attr]
            max_d = int(entry["maxDepth"])  # type: ignore[index]
            target = float(entry["target"])  # type: ignore[index]
            lo, hi = prev + 1, max_d
            depth_label = str(lo) if lo == hi else f"{lo}-{hi}"
            lines.append(f"| {depth_label} | {target:.0%} |")
            prev = max_d

    def seg_stats(dmin: int, dmax: int) -> Tuple[float, float, int]:
        vals = [(depth_win[d], depth_tgt[d]) for d in depth_win if dmin <= d <= dmax and d in depth_tgt]
        if not vals:
            return 0.0, 0.0, 0
        avg_a = sum(a for a, _ in vals) / len(vals)
        avg_t = sum(t for _, t in vals) / len(vals)
        outside = sum(1 for a, t in vals if abs(a - t) > tol)
        return avg_a, avg_t, outside

    lines += ["", "### Depth Segments", ""]
    for name, dmin, dmax in (
        ("Early (1-25)", 1, 25),
        ("Mid (26-100)", 26, 100),
        ("Late (101-150)", 101, 150),
        ("Endgame (151-200)", 151, 200),
    ):
        avg_a, avg_t, outside = seg_stats(dmin, dmax)
        delta = avg_a - avg_t
        status = "ok" if abs(delta) <= tol else ("too easy" if delta > 0 else "too hard")
        lines.append(
            f"- **{name}**: {avg_a:.1%} (target {avg_t:.1%}, {delta:+.1%}) [{status}]"
            f" - {outside} depth(s) outside +/- {tol:g}"
        )

    outside_depths = sorted(
        d for d in depth_win if d in depth_tgt and abs(depth_win[d] - depth_tgt[d]) > tol
    )
    lines += ["", f"### Depths Outside Tolerance ({len(outside_depths)}/{len(depth_win)})", ""]
    if outside_depths:
        runs: List[List[int]] = []
        for d in outside_depths:
            if runs and d == runs[-1][-1] + 1:
                runs[-1].append(d)
            else:
                runs.append([d])
        for run in runs:
            details = " ".join(
                f"d{d}={depth_win[d]:.2f}({depth_win[d] - depth_tgt[d]:+.2f})" for d in run
            )
            label = f"d{run[0]}" if len(run) == 1 else f"d{run[0]}-{run[-1]}"
            lines.append(f"- {label}: {details}")
        lines.append("")
        lines.append("Full depth table: `tools/balance/balance_report.md`.")
    else:
        lines.append("All depths within tolerance.")

    lines.append("")
    return "\n".join(lines)


