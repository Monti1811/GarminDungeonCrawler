def parse_consumables() -> List[Dict[str, object]]:
    out = []
    for path in sorted(ITEMS_DIR.rglob("*.mc")):
        text = path.read_text(encoding="utf-8", errors="replace")
        m = re.search(r"class\s+(\w+)\s+extends\s+(\w+)", text)
        if not m or m.group(2) != "ConsumableItem":
            continue
        body = init_body(text)
        idm = re.search(r"(?:self\.)?id\s*=\s*(\d+)", body) or re.search(
            r"var\s+id\s+as\s+\w+\s*=\s*(\d+)", text
        )
        if not idm:
            continue
        out.append({
            "id": int(idm.group(1)),
            "class_name": m.group(1),
            "file": path,
            "name": quoted(body, text, "name") or m.group(1),
            "description": quoted(body, text, "description"),
            "effect": quoted(body, text, "effect_description"),
            "value": ab.parse_number_assignment(body, "value", 0),
            "weight": parse_weight(body, text),
            "sprite": get_sprite(text),
        })
    return out


def parse_specials() -> List[Dict[str, object]]:
    out = []
    for path in sorted((ITEMS_DIR / "SpecialItems").rglob("*.mc")):
        text = path.read_text(encoding="utf-8", errors="replace")
        m = re.search(r"class\s+(\w+)\s+extends\s+(\w+)", text)
        if not m:
            continue
        body = init_body(text)
        idm = re.search(r"var\s+id\s+as\s+\w+\s*=\s*(\d+)", text) or re.search(
            r"(?:self\.)?id\s*=\s*(\d+)", body
        )
        if not idm:
            continue
        out.append({
            "id": int(idm.group(1)),
            "class_name": m.group(1),
            "file": path,
            "name": quoted(body, text, "name") or m.group(1),
            "description": quoted(body, text, "description"),
            "value": ab.parse_number_assignment(body, "value", 0),
            "weight": parse_weight(body, text),
            "sprite": get_sprite(text),
        })
    return out


def item_extras(item) -> Dict[str, object]:
    text = item.file.read_text(encoding="utf-8", errors="replace")
    body = init_body(text)
    return {
        "name": quoted(body, text, "name") or item.class_name,
        "description": quoted(body, text, "description"),
        "weight": parse_weight(body, text),
        "slot": (lambda m: m.group(1) if m else None)(re.search(r"(?:self\.)?slot\s*=\s*(\w+)", body)),
        "sprite": get_sprite(text),
    }


def weapon_table(items, dmap: Dict[str, str]) -> List[str]:
    lines = [
        "| Image | Item | ID | Attack | Scales | Value | Weight | Bonus |",
        "|---|---|---:|---:|---|---:|---:|---|",
    ]
    for iid, item, extra in sorted(items, key=lambda x: x[0]):
        name = str(extra["name"])
        link = f"[{name}]({source_link(item.file)})"
        lines.append(
            f"| {img_cell(extra['sprite'], dmap)} | {link} | {iid} | {item.attack} |"
            f" {TYPE_SHORT.get(item.attack_type, item.attack_type)} | {item.value} |"
            f" {fmt_num(extra['weight'])} | {bonus_text(item.attribute_bonus)} |"
        )
    return lines


def armor_table(items, dmap: Dict[str, str]) -> List[str]:
    lines = [
        "| Image | Item | ID | Defense | Slot | Scales | Value | Weight | Bonus |",
        "|---|---|---:|---:|---|---|---:|---:|---|",
    ]
    for iid, item, extra in sorted(items, key=lambda x: x[0]):
        name = str(extra["name"])
        link = f"[{name}]({source_link(item.file)})"
        slot = extra["slot"] or "-"
        lines.append(
            f"| {img_cell(extra['sprite'], dmap)} | {link} | {iid} | {item.defense} |"
            f" {slot} | {TYPE_SHORT.get(item.defense_type, item.defense_type)} |"
            f" {item.value} | {fmt_num(extra['weight'])} | {bonus_text(item.attribute_bonus)} |"
        )
    return lines


def build_items_doc(dmap: Dict[str, str]) -> str:
    by_class, _by_id = ab.parse_item_files(WORKSPACE)
    consumables = parse_consumables()
    specials = parse_specials()

    lines: List[str] = [
        "# Item Values",
        "",
        "Current item stats, sprites and drop tables.",
        "",
        GENERATED_NOTE,
        "",
        "`Scales` is the attribute the stat scales with"
        " (`Attack` for weapons, `Defense` for armor).",
        "`Bonus` lists flat attribute bonuses from `attribute_bonus`.",
        "",
    ]

    # Group items by source folder
    groups: Dict[str, List] = {}
    for item in by_class.values():
        rel = item.file.relative_to(ITEMS_DIR)
        groups.setdefault(rel.parent.as_posix(), []).append(item)

    # Weapons by tier
    tier_folders = sorted(
        (k for k in groups if re.fullmatch(r"WeaponItems/\d+_\w+", k)),
        key=lambda k: int(k.split("/")[1].split("_")[0]),
    )
    if tier_folders:
        lines += ["## Weapons", ""]
        for key in tier_folders:
            n = int(key.split("/")[1].split("_")[0])
            rows = [(i.id, i, item_extras(i)) for i in groups[key]]
            lines += [f"### Tier {n}: {TIER_NAMES.get(n, '?')}", ""]
            lines += weapon_table(rows, dmap)
            lines.append("")

    # Armor by tier
    armor_folders = sorted(
        (k for k in groups if re.fullmatch(r"ArmorItems/Armors/\d+_\w+", k)),
        key=lambda k: int(k.split("/")[2].split("_")[0]),
    )
    if armor_folders:
        lines += ["## Armor", ""]
        for key in armor_folders:
            n = int(key.split("/")[2].split("_")[0])
            rows = [(i.id, i, item_extras(i)) for i in groups[key]]
            lines += [f"### Tier {n}: {TIER_NAMES.get(n, '?')}", ""]
            lines += armor_table(rows, dmap)
            lines.append("")

    # Fixed groups (shields, backpacks, ammo, ...)
    for key, title in FIXED_ITEM_GROUPS:
        if key not in groups:
            continue
        rows = [(i.id, i, item_extras(i)) for i in groups[key]]
        is_armor = key.startswith("ArmorItems")
        lines += [title, ""]
        lines += armor_table(rows, dmap) if is_armor else weapon_table(rows, dmap)
        lines.append("")

    # Any unknown folders
    known = set(tier_folders) | set(armor_folders) | {k for k, _ in FIXED_ITEM_GROUPS}
    for key in sorted(set(groups) - known):
        rows = [(i.id, i, item_extras(i)) for i in groups[key]]
        is_armor = rows[0][1].kind == "armor"
        lines += [f"## {key}", ""]
        lines += armor_table(rows, dmap) if is_armor else weapon_table(rows, dmap)
        lines.append("")

    # Consumables
    if consumables:
        lines += [
            "## Consumables",
            "",
            "| Image | Item | ID | Effect | Value | Weight |",
            "|---|---|---:|---|---:|---:|",
        ]
        for c in sorted(consumables, key=lambda x: x["id"]):  # type: ignore[var-annotated]
            name = str(c["name"])
            link = f"[{name}]({source_link(c['file'])})"  # type: ignore[arg-type]
            effect = str(c["effect"]) or str(c["description"])
            lines.append(
                f"| {img_cell(c['sprite'], dmap)} | {link} | {c['id']} | {effect} |"
                f" {c['value']} | {fmt_num(c['weight'])} |"
            )
        lines.append("")

    # Special items
    if specials:
        lines += [
            "## Special Items",
            "",
            "| Image | Item | ID | Description | Value | Weight |",
            "|---|---|---:|---|---:|---:|",
        ]
        for c in sorted(specials, key=lambda x: x["id"]):  # type: ignore[var-annotated]
            name = str(c["name"])
            link = f"[{name}]({source_link(c['file'])})"  # type: ignore[arg-type]
            lines.append(
                f"| {img_cell(c['sprite'], dmap)} | {link} | {c['id']} |"
                f" {c['description']} | {c['value']} | {fmt_num(c['weight'])} |"
            )
        lines.append("")

    # Drop weights
    tables = ab.parse_item_weight_tables(WORKSPACE)
    bodies = tables.method_bodies
    consumable_body = bodies.get("buildConsumableWeights", "")
    cross_tiers = ab.parse_item_inline_tiers(consumable_body)
    weight_sections = [
        ("Weapons", bodies.get("buildWeaponWeights", "")),
        ("Armor", bodies.get("buildArmorWeights", "")),
        ("Consumables", consumable_body),
        ("High Quality", bodies.get("buildHighQualityWeights", "")),
        ("Merchant", bodies.get("buildMerchantWeights", "")),
    ]
    rendered = False
    for title, body in weight_sections:
        rows = ab.parse_item_weight_report(body, cross_tiers=cross_tiers)
        if not rows:
            continue
        if not rendered:
            lines += [
                "## Item Drop Weights",
                "",
                "Current tiered drop weights from `ItemSpecificValues.mc`"
                " (`build*Weights`).",
                "",
            ]
            rendered = True
        lines += [
            f"### {title}",
            "",
            "| Weight | Item IDs | Tiers (depth <= max: weight) |",
            "|---|---|---|",
        ]
        for display, ids, tiers_text in rows:
            lines.append(f"| {display} | {', '.join(str(i) for i in ids)} | {tiers_text} |")
        lines.append("")

    lines.append("")
    return "\n".join(lines)


def main() -> None:
    DOC_DIR.mkdir(parents=True, exist_ok=True)
    dmap = load_drawables()
    write_doc("enemies-values.md", build_enemies_doc(dmap))
    write_doc("items-values.md", build_items_doc(dmap))


if __name__ == "__main__":
    main()
